create table password_reset_requests (
    request_id uuid primary key,
    address_digest varchar(64) not null,
    user_id bigint,
    credential_version bigint,
    code_digest varchar(64) not null,
    delivery_accepted boolean not null default false,
    expires_at timestamp with time zone not null,
    failed_attempts integer not null default 0,
    terminal_at timestamp with time zone,
    constraint ck_password_reset_failed_attempts check (failed_attempts between 0 and 5)
);

create index ix_password_reset_requests_address_active
    on password_reset_requests(address_digest, terminal_at);
create index ix_password_reset_requests_tombstones
    on password_reset_requests(terminal_at);
create index ix_password_reset_requests_expiry
    on password_reset_requests(expires_at);

create table password_reset_events (
    id bigint generated by default as identity primary key,
    address_digest varchar(64) not null,
    ip_digest varchar(64) not null,
    occurred_at timestamp with time zone not null
);

create index ix_password_reset_events_address_time
    on password_reset_events(address_digest, occurred_at);
create index ix_password_reset_events_ip_time
    on password_reset_events(ip_digest, occurred_at);
create index ix_password_reset_events_cleanup
    on password_reset_events(occurred_at);
