alter table users
    add column credential_version bigint not null default 0;

alter table users
    add constraint ck_users_credential_version check (credential_version >= 0);

create table email_identity_locks (
    normalized_email varchar(255) primary key
);

insert into email_identity_locks (normalized_email)
select distinct email from users;

create table pending_email_changes (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    normalized_new_email varchar(255) not null,
    verification_code_hash varchar(255) not null,
    code_expires_at timestamp with time zone not null,
    expires_at timestamp with time zone not null,
    resend_available_at timestamp with time zone not null,
    resend_count integer not null default 0,
    failed_attempt_count integer not null default 0,
    created_at timestamp with time zone not null default current_timestamp,
    updated_at timestamp with time zone not null default current_timestamp,
    constraint fk_pending_email_changes_user foreign key (user_id) references users(id),
    constraint uq_pending_email_changes_user unique (user_id),
    constraint ck_pending_email_changes_resend_count check (resend_count >= 0),
    constraint ck_pending_email_changes_failed_attempt_count check (failed_attempt_count >= 0)
);

create table credential_security_events (
    id bigint generated by default as identity primary key,
    user_id bigint not null,
    event_type varchar(64) not null,
    normalized_target_email varchar(255),
    occurred_at timestamp with time zone not null,
    constraint fk_credential_security_events_user foreign key (user_id) references users(id),
    constraint ck_credential_security_events_type check (event_type in (
        'CURRENT_PASSWORD_FAILURE',
        'EMAIL_CHANGE_START',
        'EMAIL_VERIFICATION_DELIVERY'
    ))
);

create index ix_credential_security_events_user_type_time
    on credential_security_events(user_id, event_type, occurred_at);

create index ix_credential_security_events_target_type_time
    on credential_security_events(normalized_target_email, event_type, occurred_at);
